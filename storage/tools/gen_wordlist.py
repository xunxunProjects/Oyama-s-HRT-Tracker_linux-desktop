#!/usr/bin/env python3
"""Generate the compiled EFF long Diceware wordlist.

The source list is the EFF long wordlist from
https://www.eff.org/files/2016/07/18/eff_large_wordlist.txt
(CC BY 3.0).  The checked-in text file has one word per line, in the
original six-dice order.
"""

from __future__ import annotations

import pathlib
import re
import sys

WORD_COUNT = 7776
WORD_RE = re.compile(r"^[a-z]+(?:-[a-z]+)*$")


def main() -> int:
    repo_root = pathlib.Path(__file__).resolve().parents[2]
    source = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else repo_root / "vault" / "data" / "eff_long_wordlist.txt"
    destination = pathlib.Path(sys.argv[2]) if len(sys.argv) > 2 else repo_root / "storage" / "src" / "passphrase_wordlist.cpp"

    words = source.read_text(encoding="utf-8").splitlines()
    if len(words) != WORD_COUNT:
        raise SystemExit(f"expected {WORD_COUNT} words, found {len(words)}")
    if len(set(words)) != WORD_COUNT:
        raise SystemExit("wordlist contains duplicate words")
    for word in words:
        if not WORD_RE.fullmatch(word):
            raise SystemExit(f"invalid word: {word!r}")

    lines = [
        "// Generated by storage/tools/gen_wordlist.py. Do not edit.",
        "// EFF long Diceware wordlist, CC BY 3.0.",
        "// https://www.eff.org/files/2016/07/18/eff_large_wordlist.txt",
        "",
        "#include <array>",
        "#include <string_view>",
        "",
        "namespace oyama::storage::detail {",
        "",
        "extern const std::array<std::string_view, 7776> kWordlist = {{",
    ]
    lines.extend(f'    "{word}",' for word in words)
    lines.extend(["}};", "", "}  // namespace oyama::storage::detail", ""])

    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {destination} ({len(words)} words)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
